#!/usr/bin/env bash
# Prepares the npm and PyPI packages for a Wardmap release tag.
#
# The SHA-256 values baked into both packages come only from the release's
# checksums.txt, accepted only after its Sigstore signature verifies against
# this repository's release workflow at that exact tag.
#
# Usage: packaging/render.sh vX.Y.Z    (needs curl and cosign)
set -euo pipefail

tag="${1:?usage: packaging/render.sh vX.Y.Z}"
if ! [[ "$tag" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "error: unexpected tag '$tag'" >&2
  exit 1
fi
version="${tag#v}"
repo="Breaktroughf1/wardmap"
here="$(cd "$(dirname "$0")" && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

for f in checksums.txt checksums.txt.sigstore.json; do
  curl --fail --silent --show-error --location --retry 3 --proto '=https' -o "$work/$f" "https://github.com/${repo}/releases/download/${tag}/$f"
done
cosign verify-blob --bundle "$work/checksums.txt.sigstore.json" \
  --certificate-identity "https://github.com/${repo}/.github/workflows/release.yml@refs/tags/${tag}" \
  --certificate-oidc-issuer https://token.actions.githubusercontent.com "$work/checksums.txt"

python3 - "$version" "$work/checksums.txt" "$here" <<'PY'
import json, pathlib, re, sys
version, sums_path, here = sys.argv[1], sys.argv[2], pathlib.Path(sys.argv[3])
want = [f"wardmap_{version}_{o}_{a}.{'zip' if o == 'windows' else 'tar.gz'}"
        for o in ("darwin", "linux", "windows") for a in ("amd64", "arm64")]
sums = {}
for line in pathlib.Path(sums_path).read_text().splitlines():
    digest, name = line.split()
    if name in want:
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            sys.exit(f"bad checksum for {name}")
        sums[name] = digest
missing = sorted(set(want) - set(sums))
if missing:
    sys.exit(f"checksums.txt lacks {missing}")
release = {"version": version, "checksums": dict(sorted(sums.items()))}
(here / "npm/lib/release.json").write_text(json.dumps(release, indent=2) + "\n")
pkg = json.loads((here / "npm/package.json").read_text())
pkg["version"] = version
(here / "npm/package.json").write_text(json.dumps(pkg, indent=2) + "\n")
(here / "pypi/src/wardmap/_release.py").write_text(
    "# Generated by packaging/render.sh from the Sigstore-verified checksums.txt. Do not edit.\n"
    f"VERSION = {version!r}\n"
    f"CHECKSUMS = {json.dumps(dict(sorted(sums.items())), indent=4)}\n")
pyproject = here / "pypi/pyproject.toml"
pyproject.write_text(re.sub(r'(?m)^version = ".*"$', f'version = "{version}"', pyproject.read_text(), count=1))
print(f"rendered npm and PyPI packages for wardmap {version}")
PY
cp "$here/../LICENSE" "$here/npm/LICENSE"
cp "$here/../LICENSE" "$here/pypi/LICENSE"
